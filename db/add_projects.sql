--  Description: The projects of a profile: something the reader prepares for a time (a trip, a purchase,
--               a report), written with the AI as a profile is, split into interests the briefing reads
--               with the profile's own until the project ends
--
-- A project has interests as a profile has (profile_interests, id_project set): the briefing ranks the
-- stories on them too, from the same sources as the profile. No source is found for a project (the
-- discovery reads the profile's own interests only); the searches of Google News of its interests are
-- read while it runs. An ended project is kept, and read no more, until the reader deletes it.
-- Additive: the server of before reads every interest of a profile, a project's too (the ranking below
-- leaves out the ones of an ended project).

CREATE TABLE IF NOT EXISTS public.profile_projects (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_profile integer NOT NULL REFERENCES public.user_profiles(id) ON DELETE CASCADE,
    name       text NOT NULL,
    text       text NOT NULL,
    ends_on    date,                -- the last day it is read, none: until the reader deletes it
    created_at timestamp with time zone NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS i_profile_projects_profile ON public.profile_projects (id_profile);

-- an interest of a project goes with it
ALTER TABLE public.profile_interests ADD COLUMN IF NOT EXISTS id_project integer
    REFERENCES public.profile_projects(id) ON DELETE CASCADE;
CREATE INDEX IF NOT EXISTS i_profile_interests_project ON public.profile_interests (id_project) WHERE id_project IS NOT NULL;

-- the stories closest to the interests of a profile and of its projects running (see add_profiles.sql)
CREATE OR REPLACE FUNCTION public.rank_profile_stories(profile_id integer, feed_urls text[], languages text[], since timestamptz,
                                                       sparse_weight real, excluded integer[], max_stories integer)
    RETURNS TABLE (id_story integer, id_article integer, id_interest integer, score double precision)
    LANGUAGE sql
    STABLE
AS $$
    WITH visible AS (
        -- a news in several feeds of the user is scored once
        SELECT DISTINCT ON (a.link) a.id, a.id_story, a.text_dense, a.text_sparse
        FROM articles a
        JOIN feeds f ON f.id = a.id_feed
        WHERE f.url = ANY(feed_urls)
          AND (languages IS NULL OR a.lang = ANY(languages))   -- NULL: every language, translated for the reader
          AND a.embedded_at IS NOT NULL
          AND a.id_story IS NOT NULL
          AND a.id_story <> ALL(COALESCE(excluded, '{}'))
          AND COALESCE(a.published_at, a.created_at) >= since
        ORDER BY a.link, COALESCE(a.published_at, a.created_at) DESC
    ), interests AS MATERIALIZED (       -- a dozen rows, read once
        SELECT i.id, i.weight, i.dense, i.sparse
        FROM profile_interests i
        LEFT JOIN profile_projects p ON p.id = i.id_project
        WHERE i.id_profile = profile_id AND i.dense IS NOT NULL
          AND (i.id_project IS NULL OR p.ends_on IS NULL OR p.ends_on >= current_date)
    ), scored AS (
        SELECT v.id, v.id_story, best.id AS id_interest, best.score
        FROM visible v
        CROSS JOIN LATERAL (
            SELECT i.id, i.weight * (-(v.text_dense <#> i.dense) - sparse_weight * (v.text_sparse <#> i.sparse)) AS score
            FROM interests i
            ORDER BY 2 DESC
            LIMIT 1
        ) best
    )
    SELECT s.id_story, s.id, s.id_interest, s.score
    FROM (SELECT DISTINCT ON (id_story) id_story, id, id_interest, score FROM scored ORDER BY id_story, score DESC) s
    ORDER BY s.score DESC
    LIMIT max_stories
$$;
